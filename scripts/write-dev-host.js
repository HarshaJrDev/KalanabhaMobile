#!/usr/bin/env node













const fs = require('fs');
const os = require('os');
const path = require('path');

const pickLanIp = () => {
    const interfaces = os.networkInterfaces();
    
    
    const preferredOrder = ['en0', 'en1', 'Wi-Fi', 'eth0'];
    const candidates = [];

    for (const [name, addrs] of Object.entries(interfaces)) {
        for (const addr of addrs ?? []) {
            if (addr.family === 'IPv4' && !addr.internal) {
                candidates.push({ name, address: addr.address });
            }
        }
    }

    for (const preferred of preferredOrder) {
        const found = candidates.find((c) => c.name === preferred);
        if (found) return found.address;
    }

    return candidates[0]?.address ?? null;
};

const ip = pickLanIp();
const outPath = path.join(__dirname, '..', 'src', 'config', 'devHost.generated.ts');

if (!ip) {
    console.warn('[write-dev-host] Could not detect a LAN IP — falling back to localhost. ' +
        'A physical device will not be able to reach the backend; an emulator/simulator still will via its own loopback alias.');
}

const contents = `// AUTO-GENERATED by scripts/write-dev-host.js — do not edit by hand.
// Regenerated fresh on every \`npm run android\`/\`ios\`/\`start\`.
export const DEV_HOST = ${JSON.stringify(ip ?? 'localhost')};
`;

fs.writeFileSync(outPath, contents);
console.log(`[write-dev-host] DEV_HOST = ${ip ?? 'localhost'} -> ${path.relative(process.cwd(), outPath)}`);
